# ✅ Arithmetic Operators
# Take a number as input and print its square and cube using the exponent operator (**).

a1 = int(input("Enter the number to find the square = "))
a2 = 2

square = a1 ** a2
print("The square of the number is = ",square)

b1 = int(input("Enter the number to find the cube = "))
b2 = 3

cube = b1 ** b2 
print("The cube of the given number is = ",cube)