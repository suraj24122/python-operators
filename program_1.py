# ✅ Arithmetic Operators
# **Write a program to perform all arithmetic operations (+, -, *, /, %) on two numbers.

# 1. Get two numbers from the user.
first_number = int(input("Enter the number 1 = "))
sec_number = int(input("Enter the number 2 = "))

addition = first_number + sec_number
subtract = first_number - sec_number
multiply = first_number * sec_number
division = first_number / sec_number
modulous = first_number % sec_number

print("The addition of the two numbers are = ",addition)
print("The subtraction of the two numbers are = ",subtract)
print("The multiply of the two numbers are = ",multiply)
print("The division of the two numbers are = ",division)
print("The modulous of the two numbers are = ",modulous)
